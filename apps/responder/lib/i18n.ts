export function roleLabel(role: string | null | undefined, locale: Locale): string {
  const labels: Record<Locale, Record<string, string>> = {
    en: { PRIMARY: "primary", BACKUP: "backup", TERTIARY: "third" },
    ar: { PRIMARY: "الأساسية", BACKUP: "الاحتياطية", TERTIARY: "الثالثة" },
  };
  return labels[locale][role ?? ""] ?? (locale === "ar" ? "المختارة" : "selected");
}
